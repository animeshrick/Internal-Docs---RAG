-- 06_salary_and_payslips.sql
-- Run once in the Supabase SQL Editor, AFTER 03 and 04. Safe to run again.
--
-- What it adds:
--   1. salary_components  one row per part of a salary (Basic, HRA, PF ...), per employee
--   2. payslips           one row per employee per month, pointing to a PDF in a private bucket
--   3. a private storage bucket "payslips"
--
-- The monthly gross salary itself stays in employee.salary (already exists).
-- Only our server (secret key) can read these tables. Rules about who may see what are in app/payroll_service.py:
--   an employee sees only their own salary and payslips, HR can ask about any employee.
--
-- To fill the breakdown of one employee, add rows in the Table Editor (or SQL), for example:
--   insert into public.salary_components (employee_id, component_name, component_type, monthly_amount)
--   select id, 'Basic', 'earning', 40000 from public.employee where emp_id = 'EMP003';

create table if not exists public.salary_components (
    id bigint generated by default as identity primary key,
    employee_id bigint not null references public.employee (id) on delete cascade,
    component_name text not null,                                       -- Basic, HRA, Provident Fund ...
    component_type text not null check (component_type in ('earning', 'deduction')),
    monthly_amount numeric not null check (monthly_amount >= 0),
    sort_order int not null default 0,
    update_at timestamptz not null default now(),
    unique (employee_id, component_name)
);

create index if not exists salary_components_employee_idx on public.salary_components (employee_id);

create table if not exists public.payslips (
    id bigint generated by default as identity primary key,
    employee_id bigint not null references public.employee (id) on delete cascade,
    pay_month date not null check (extract(day from pay_month) = 1),   -- always the first day of the month
    net_pay numeric null,
    file_path text not null,                                            -- path inside the private "payslips" bucket
    created_at timestamptz not null default now(),
    unique (employee_id, pay_month)
);

create index if not exists payslips_employee_month_idx on public.payslips (employee_id, pay_month desc);

alter table public.salary_components enable row level security;
alter table public.payslips enable row level security;

do $$
begin
    if exists (select 1 from information_schema.schemata where schema_name = 'storage') then
        insert into storage.buckets (id, name, public)
        values ('payslips', 'payslips', false)
        on conflict (id) do nothing;
    end if;
end $$;
