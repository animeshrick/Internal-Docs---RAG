-- 03_employee_and_auth.sql
-- Run once in the Supabase SQL Editor.
-- It creates the "employee" table (with the corrected design) and the login table "employee_auth".
-- Safe to run again: both tables use "if not exists", so existing rows are never touched.
-- Differences from the first version of the table: full_name (was full_namae), emp_id is unique and is the
-- login id, phone numbers are text, dob and doj are plain dates, update_at updates itself.

-- ---------------------------------------------------------------- 1. the employee table
create table if not exists public.employee (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    full_name varchar not null,
    emp_id varchar not null unique,                 -- the login id, for example EMP001
    email varchar not null unique,
    is_active boolean not null default true,
    phone text null unique,                         -- text, so leading zeros and country codes are kept
    full_current_address varchar null,
    image varchar null,
    emergency_ph_no text null,
    salary numeric null,
    doj date null,                                  -- date of joining
    dob date null,                                  -- date of birth (used in the temporary password)
    dept varchar null,                              -- IT, Sales, Design, VideoEditor ... (not used for roles)
    update_at timestamptz not null default now()
);

-- Keep update_at correct automatically (also used by employee_auth below).
create or replace function public.set_update_at()
returns trigger
language plpgsql
as $$
begin
    new.update_at = now();
    return new;
end;
$$;

drop trigger if exists employee_set_update_at on public.employee;
create trigger employee_set_update_at
    before update on public.employee
    for each row execute function public.set_update_at();

-- Only our server (secret key) may read this table. The public anon key reads nothing.
alter table public.employee enable row level security;


-- ---------------------------------------------------------------- 2. the login table
create table if not exists public.employee_auth (
    employee_id bigint primary key references public.employee (id) on delete cascade,
    password_hash text not null,                        -- bcrypt hash, never the real password
    role text not null default 'employee'
        check (role in ('employee', 'hr', 'ceo')),     -- set by HR, not read from dept
    must_change_password boolean not null default true, -- true until the person sets their own password
    failed_login_attempts integer not null default 0,
    locked_until timestamptz null,                      -- set after too many wrong passwords
    password_changed_at timestamptz null,
    created_at timestamptz not null default now(),
    update_at timestamptz not null default now()
);

drop trigger if exists employee_auth_set_update_at on public.employee_auth;
create trigger employee_auth_set_update_at
    before update on public.employee_auth
    for each row execute function public.set_update_at();

alter table public.employee_auth enable row level security;
